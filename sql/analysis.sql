-- Q1. 치료부위와 치료유형별로 몇 명의 환자가 치료를 받았는가?

SELECT
    BODY_PART,
    TREATMENT_TYPE,
    COUNT(DISTINCT PATIENT_ID) AS PATIENT_CNT
FROM TREATMENT_RECORD
GROUP BY BODY_PART, TREATMENT_TYPE
ORDER BY BODY_PART, TREATMENT_TYPE;


-- Q2. 환자별 총 치료 횟수, 치료기간, 주당 치료빈도는 얼마인가?

SELECT
    PATIENT_ID,
    COUNT(*) AS TREATMENT_CNT,
    MIN(TREATMENT_DATE) AS FIRST_VISIT,
    MAX(TREATMENT_DATE) AS LAST_VISIT,
    DATEDIFF(MAX(TREATMENT_DATE), MIN(TREATMENT_DATE)) + 1 AS DURATION,
    ROUND(
        COUNT(*) * 7.0 /
        (DATEDIFF(MAX(TREATMENT_DATE), MIN(TREATMENT_DATE)) + 1),
        2
    ) AS WEEKLY_FREQUENCY
FROM TREATMENT_RECORD
GROUP BY PATIENT_ID
ORDER BY PATIENT_ID;


-- Q3. 환자별 첫 통증점수와 마지막 통증점수는 얼마나 변했는가?

SELECT DISTINCT
    PATIENT_ID,

    FIRST_VALUE(PAIN_SCORE) OVER (
        PARTITION BY PATIENT_ID
        ORDER BY ASSESSMENT_DATE
    ) AS FIRST_PAIN,

    LAST_VALUE(PAIN_SCORE) OVER (
        PARTITION BY PATIENT_ID
        ORDER BY ASSESSMENT_DATE
        ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
    ) AS LAST_PAIN,

    FIRST_VALUE(PAIN_SCORE) OVER (
        PARTITION BY PATIENT_ID
        ORDER BY ASSESSMENT_DATE
    )
    -
    LAST_VALUE(PAIN_SCORE) OVER (
        PARTITION BY PATIENT_ID
        ORDER BY ASSESSMENT_DATE
        ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
    ) AS PAIN_IMPROVEMENT

FROM PAIN_ASSESSMENT
ORDER BY PATIENT_ID;


-- Q4. 치료빈도에 따라 통증 변화는 어떻게 달랐는가?

WITH T AS (
    SELECT
        PATIENT_ID,
        ROUND(
            COUNT(*) * 7.0 /
            (DATEDIFF(MAX(TREATMENT_DATE), MIN(TREATMENT_DATE)) + 1),
            2
        ) AS WEEKLY_FREQUENCY
    FROM TREATMENT_RECORD
    GROUP BY PATIENT_ID
),

P AS (
    SELECT DISTINCT
        PATIENT_ID,

        FIRST_VALUE(PAIN_SCORE) OVER (
            PARTITION BY PATIENT_ID
            ORDER BY ASSESSMENT_DATE
        ) AS FIRST_PAIN,

        LAST_VALUE(PAIN_SCORE) OVER (
            PARTITION BY PATIENT_ID
            ORDER BY ASSESSMENT_DATE
            ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
        ) AS LAST_PAIN

    FROM PAIN_ASSESSMENT
),

BASE AS (
    SELECT
        T.PATIENT_ID,
        T.WEEKLY_FREQUENCY,
        P.FIRST_PAIN - P.LAST_PAIN AS PAIN_IMPROVEMENT,

        CASE
            WHEN T.WEEKLY_FREQUENCY < 1
                THEN 'LESS_THAN_1_PER_WEEK'

            WHEN T.WEEKLY_FREQUENCY < 2
                THEN '1_TO_LESS_THAN_2_PER_WEEK'

            ELSE '2_OR_MORE_PER_WEEK'
        END AS FREQUENCY_GROUP

    FROM T
    JOIN P
        ON T.PATIENT_ID = P.PATIENT_ID
)

SELECT
    FREQUENCY_GROUP,
    COUNT(*) AS PATIENT_CNT,
    ROUND(AVG(WEEKLY_FREQUENCY), 2) AS AVG_WEEKLY_FREQUENCY,
    ROUND(AVG(PAIN_IMPROVEMENT), 2) AS AVG_PAIN_IMPROVEMENT
FROM BASE
GROUP BY FREQUENCY_GROUP
ORDER BY MIN(WEEKLY_FREQUENCY);


-- Q5. 치료부위와 치료유형에 따라 치료 횟수, 치료빈도, 통증 변화는 어떻게 달랐는가?

WITH A AS (
    SELECT DISTINCT
        PATIENT_ID,
        BODY_PART,
        TREATMENT_TYPE
    FROM TREATMENT_RECORD
),

T AS (
    SELECT
        PATIENT_ID,
        COUNT(*) AS TREATMENT_CNT,

        ROUND(
            COUNT(*) * 7.0 /
            (DATEDIFF(MAX(TREATMENT_DATE), MIN(TREATMENT_DATE)) + 1),
            2
        ) AS WEEKLY_FREQUENCY

    FROM TREATMENT_RECORD
    GROUP BY PATIENT_ID
),

P AS (
    SELECT DISTINCT
        PATIENT_ID,

        FIRST_VALUE(PAIN_SCORE) OVER (
            PARTITION BY PATIENT_ID
            ORDER BY ASSESSMENT_DATE
        ) AS FIRST_PAIN,

        LAST_VALUE(PAIN_SCORE) OVER (
            PARTITION BY PATIENT_ID
            ORDER BY ASSESSMENT_DATE
            ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
        ) AS LAST_PAIN

    FROM PAIN_ASSESSMENT
)

SELECT
    A.BODY_PART,
    A.TREATMENT_TYPE,
    COUNT(DISTINCT A.PATIENT_ID) AS PATIENT_CNT,
    ROUND(AVG(T.TREATMENT_CNT), 2) AS AVG_TREATMENT_CNT,
    ROUND(AVG(T.WEEKLY_FREQUENCY), 2) AS AVG_WEEKLY_FREQUENCY,
    ROUND(AVG(P.FIRST_PAIN - P.LAST_PAIN), 2) AS AVG_PAIN_IMPROVEMENT

FROM A
JOIN T
    ON A.PATIENT_ID = T.PATIENT_ID
JOIN P
    ON A.PATIENT_ID = P.PATIENT_ID

GROUP BY
    A.BODY_PART,
    A.TREATMENT_TYPE

ORDER BY
    A.BODY_PART,
    A.TREATMENT_TYPE;